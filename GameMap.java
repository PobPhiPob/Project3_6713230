    public void nextLevel() {
        currentLevel++;
        if (currentLevel >= allmapData.length) {
            currentLevel = 0;
        }
    }

    public boolean isSolid(int x, int y) {
        int col = x / TILE_SIZE;
        int row = y / TILE_SIZE;
        int[][] currentmapData = allmapData[currentLevel];

        if (col < 0 || col >= currentmapData[0].length || row < 0 || row >= currentmapData.length) {
            return false;
        }
        return currentmapData[row][col] != 0; 
    }
    
    //usefordebug
    public void drawMap(JLabel drawpane) {
        int[][] currentMapData = allmapData[currentLevel]; 

        for (int row = 0; row < currentMapData.length; row++) {
            for (int col = 0; col < currentMapData[0].length; col++) {
                
                if (currentMapData[row][col] == 1) { 
                    
                    JLabel debugTile = new JLabel();
                    
                    debugTile.setBounds(col * TILE_SIZE, row * TILE_SIZE, TILE_SIZE, TILE_SIZE);
                    
                    debugTile.setOpaque(false); 
                    
                    debugTile.setBorder(BorderFactory.createLineBorder(Color.RED));

                    drawpane.add(debugTile);
                }
            }
        }
    }

